export function naturalHanziClue(character, clue) {
  if (!clue.includes('□')) return clue;
  if (CLUES[character]) return CLUES[character];
  // 保留原提示中完整的生活情境，去掉需要看方框补词的分句。
  const prefix = clue.slice(0, clue.indexOf('□'));
  const descriptions = prefix.split(/[，。；：？！]/u).slice(0, -1)
    .filter(part => part.trim() && !/^(问|说|叫|可以说|想想)$/u.test(part));
  const following = clue.match(/□(\p{Script=Han})/u)?.[1];
  const preceding = prefix.match(/(\p{Script=Han})$/u)?.[1];
  const neighbor = following || preceding;
  const questions = neighbor ? [
    `想一想，“${neighbor}”${following ? '前面' : '后面'}接什么字？`,
    `旁边是“${neighbor}”，你还记得它的读音吗？`,
    '回忆一下读音。'
  ] : ['想想这个字怎么读。', '回忆一下读音。'];
  const question = questions.find(text => !text.includes(character));
  return `${descriptions.length ? `${descriptions.join('，')}。` : ''}${question}`;
}

export function naturalSpeechText(text) {
  return String(text || '')
    .replace(/[（(【\[]\s*[）)】\]]/gu, '问号')
    .replace(/[（(）)【】\[\]]/gu, '，')
    .replace(/[□_]+/gu, '问号')
    .replace(/[，,]\s*([，。？！])/gu, '$1')
    .replace(/^[，,]+|[，,]+$/gu, '')
    .trim();
}
